from types import SimpleNamespace
from typing import Any

import streamlit as st

from lpr_cpe_demo.benchmarks import BANDS, citation
from lpr_cpe_demo.effort import assumptions, false_positive_cost
from lpr_cpe_demo.fault_generator import generate_faults, summarise
from lpr_cpe_demo.geo_layers import (
    COST_BANDS,
    FAULT_TOOLTIP,
    OSM_ATTRIBUTION,
    OSM_POLICY_URL,
    ROUTE_CAVEAT,
    fault_records,
    road_leg_records,
    routing_summary,
)
from lpr_cpe_demo.routing import ROUTING_NOTE, router_from_env
